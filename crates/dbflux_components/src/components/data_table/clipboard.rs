use super::model::{CellKind, CellValue, TableModel};
use super::selection::{CellCoord, SelectionState};

/// Format a single cell value for clipboard (TSV compatible).
pub fn format_cell(cell: &CellValue) -> String {
    match &cell.kind {
        CellKind::Null => "".to_string(),
        CellKind::Bool(b) => if *b { "true" } else { "false" }.to_string(),
        CellKind::Int(i) => i.to_string(),
        CellKind::Float(f) => f.to_string(),
        CellKind::Text(s) | CellKind::Json(s) => escape_tsv(s),
        CellKind::Bytes(len) => format!("<{} bytes>", len),
        CellKind::Unsupported(type_name) => format!("UNSUPPORTED<{}>", type_name),
        CellKind::AutoGenerated(expr) => format!("<{}>", expr),
        CellKind::Missing => String::new(),
        CellKind::Nested { .. } => cell.display_text().to_string(),
    }
}

/// Escape a string for TSV format.
/// Replaces tabs and newlines with spaces.
fn escape_tsv(s: &str) -> String {
    s.replace(['\t', '\n'], " ").replace('\r', "")
}

/// Copy a single cell to clipboard format.
#[allow(dead_code)]
pub fn copy_cell(model: &TableModel, coord: CellCoord) -> Option<String> {
    model.cell(coord.row, coord.col).map(format_cell)
}

/// Copy an entire row to clipboard format (TSV).
#[allow(dead_code)]
pub fn copy_row(model: &TableModel, row: usize) -> Option<String> {
    model.rows.get(row).map(|row_data| {
        row_data
            .cells
            .iter()
            .map(format_cell)
            .collect::<Vec<_>>()
            .join("\t")
    })
}

/// Copy the current selection to clipboard format (TSV).
///
/// With several ranges (Ctrl+click), the text covers every row that holds a
/// selected cell and every column that does, the columns in the order the
/// grid shows them; a cell outside the selection inside that grid is left
/// empty. For one range this is the range itself. A hidden column is never
/// part of a selection, so it is never copied.
pub fn copy_selection(model: &TableModel, selection: &SelectionState) -> Option<String> {
    let ranges = selection.ranges();
    if ranges.is_empty() {
        return None;
    }
    let rows: std::collections::BTreeSet<usize> = ranges
        .iter()
        .flat_map(|range| range.start.row..=range.end.row)
        .collect();
    let mut cols: Vec<usize> = ranges
        .iter()
        .flat_map(|range| range.start.col..=range.end.col)
        .collect::<std::collections::BTreeSet<usize>>()
        .into_iter()
        .collect();
    selection.sort_by_screen_order(&mut cols);

    let lines: Vec<String> = rows
        .iter()
        .map(|&row| {
            cols.iter()
                .map(|&col| {
                    if selection.is_selected(CellCoord::new(row, col)) {
                        model.cell(row, col).map(format_cell).unwrap_or_default()
                    } else {
                        String::new()
                    }
                })
                .collect::<Vec<_>>()
                .join("\t")
        })
        .collect();

    Some(lines.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_format_cell() {
        assert_eq!(format_cell(&CellValue::null()), "");
        assert_eq!(format_cell(&CellValue::bool(true)), "true");
        assert_eq!(format_cell(&CellValue::int(42)), "42");
        assert_eq!(format_cell(&CellValue::float(2.5)), "2.5");
        assert_eq!(format_cell(&CellValue::text("hello")), "hello");
    }

    #[test]
    fn long_text_keeps_full_value_for_editing_and_clipboard_while_display_is_capped() {
        let full_text = format!("[{}]", "1,".repeat(150));
        assert!(full_text.len() > 200);

        let cell = CellValue::text(&full_text);

        assert!(matches!(&cell.kind, CellKind::Text(text) if text.as_ref() == full_text));
        assert_eq!(cell.edit_text(), full_text);
        assert_eq!(format_cell(&cell), full_text);

        let display = cell.display_text();
        assert_eq!(display.chars().count(), 201);
        assert!(display.ends_with('…'));
        assert_eq!(display.as_ref(), format!("{}…", &full_text[..200]));
    }

    #[test]
    fn test_escape_tsv() {
        assert_eq!(escape_tsv("hello\tworld"), "hello world");
        assert_eq!(escape_tsv("line1\nline2"), "line1 line2");
    }

    #[test]
    fn copy_of_separate_rows_holds_only_those_rows() {
        use super::super::model::{ColumnKind, ColumnSpec, RowData};

        let columns = ["id", "name"]
            .into_iter()
            .map(|name| ColumnSpec {
                id: name.into(),
                title: name.into(),
                kind: ColumnKind::Text,
                align: gpui::TextAlign::Left,
                type_name: "text".into(),
            })
            .collect();
        let rows = (0..4)
            .map(|i| RowData {
                cells: vec![CellValue::int(i), CellValue::text(&format!("row{i}"))],
            })
            .collect();
        let model = TableModel::new(columns, rows);

        let mut selection = SelectionState::new();
        selection.select_row(1, 2);
        selection.toggle_row(3, 2);
        assert_eq!(
            copy_selection(&model, &selection).as_deref(),
            Some("1\trow1\n3\trow3")
        );

        // Scattered cells: the grid of their rows and columns, gaps empty.
        let mut selection = SelectionState::new();
        selection.select_cell(CellCoord::new(0, 0));
        selection.toggle_cell(CellCoord::new(2, 1));
        assert_eq!(
            copy_selection(&model, &selection).as_deref(),
            Some("0\t\n\trow2")
        );
    }
}
